const createAllExample = `from sqlalchemy import Column, Integer, MetaData, String, Table, create_engine, inspect

engine = create_engine("sqlite:///:memory:")
old = MetaData()
Table("book", old, Column("id", Integer, primary_key=True), Column("title", String))
old.create_all(engine)

new = MetaData()
Table("book", new, Column("id", Integer, primary_key=True),
      Column("title", String), Column("year", Integer))
new.create_all(engine)
print([column["name"] for column in inspect(engine).get_columns("book")])
engine.dispose()`;

