      <Section number="06" title="Кортеж не замораживает объект внутри">
        <Lead>
          Кортеж запрещает замену своих элементов, но словарь внутри кортежа по-прежнему можно изменять.
        </Lead>
        <p>
          Представьте запечатанную упаковку, внутри которой лежит карточка с данными. Упаковка не позволяет заменить карточку другой, но открыть доступ к имеющейся карточке и исправить число страниц всё ещё можно. Кортеж (<code>tuple</code>) похож на такую упаковку: его состав фиксирован, однако содержащийся в нём словарь остаётся изменяемым.
        </p>
        <CodeBlock
          caption="Оболочка tuple неизменна, вложенная запись изменяется"
          code={'book = {"title": "Атлас", "pages": 64}\npackage = (book,)\npackage[0]["pages"] = 70\nprint(book["pages"])  # 70\n# package[0] = {"pages": 90}  # Это вызвало бы ошибку'}
        />
        <p>
          Здесь важно различать присваивание на двух уровнях. В команде <code>package[0]["pages"] = 70</code> сначала читаем элемент кортежа, затем меняем поле уже существующего словаря. В закомментированной команде <code>package[0] = ...</code> пытаемся заменить сам элемент кортежа. Первый шаг разрешён, второй запрещён. Это тот же вопрос об объекте изменения, который сопровождал весь урок.
        </p>
        <p>
          Запятая в <code>(book,)</code> обязательна для кортежа из одного элемента. Выражение <code>package[0]</code> возвращает исходный словарь, поэтому менять <code>pages</code> разрешено. А <code>package[0] = ...</code> пыталось бы заменить элемент самого кортежа и вызвало бы ошибку. Это дополнительное наблюдение о ссылках: в четырёх заданиях мы работаем со списком и словарём без кортежей.
        </p>
      </Section>

