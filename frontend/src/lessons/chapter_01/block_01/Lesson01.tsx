function FirstRunDemo() {
  const [message, setMessage] = useState("Маяк включён");
  const [output, setOutput] = useState<string | null>(null);
  const inputId = useId();
  const changedSinceRun = output !== null && output !== message;
  return (
    <section className="first-run-demo" aria-labelledby={`${inputId}-title`}>
      <div className="first-run-demo__heading">
        <div>
          <span className="first-run-demo__eyebrow">НЕБОЛЬШОЙ ЭКСПЕРИМЕНТ</span>
          <h3 id={`${inputId}-title`}>Что появится в выводе?</h3>
        </div>
        <p>Изменим сообщение и запустим демонстрацию.</p>
      </div>
      <div className="first-run-demo__workspace">
        <div className="first-run-demo__editor">
          <div className="first-run-demo__pane-title"><FileCode size={16} aria-hidden="true" /> Редактор</div>
          <div className="first-run-demo__code" aria-label={`Код: print(${JSON.stringify(message)})`}>
            <span className="first-run-demo__line" aria-hidden="true">1</span>
            <code><span className="first-run-demo__function">print</span>(<span className="first-run-demo__string">{JSON.stringify(message)}</span>)</code>
          </div>
          <label className="first-run-demo__label" htmlFor={inputId}>Текст между кавычками</label>
          <div className="first-run-demo__controls">
            <input id={inputId} value={message} onChange={(event) => setMessage(event.target.value)} />
            <button type="button" onClick={() => setOutput(message)}><Play size={15} aria-hidden="true" /> Запустить</button>
          </div>
        </div>
        <div className="first-run-demo__output" aria-live="polite" aria-atomic="true">
          <div className="first-run-demo__pane-title"><Terminal size={16} aria-hidden="true" /> Вывод</div>
          <div className={`first-run-demo__result${output === null ? " is-empty" : ""}`}>
            {output === null ? "Здесь появится результат" : output === "" ? "Пустая строка" : output}
          </div>
          <p className="first-run-demo__status">
            {changedSinceRun
              ? "Текст изменился. Запустите пример ещё раз."
              : output === null
                ? "Ожидает запуска"
                : output.length > 0 && output.trim() === ""
                  ? "В результате только пробелы."
                  : "Результат последнего запуска"}
          </p>
        </div>
        <span className="first-run-demo__connector" aria-hidden="true"><ArrowRight size={16} /></span>
      </div>
      <p className="first-run-demo__note">Это учебная модель. Настоящий код мы запустим в редакторе практики.</p>
    </section>
  );
}

