        <p>
          Здесь важно назвать объект и действие, а не смотреть только на имя слева. Переприсваивание меняет локальную связь. Мутация меняет сам список. Поэтому после каждого вызова отдельно проверим исходное имя, состояние списка и возвращённое значение, если оно предусмотрено.
        </p>
