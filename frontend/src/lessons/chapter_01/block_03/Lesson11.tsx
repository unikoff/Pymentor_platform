        <p>
          <code>None</code> означает особое значение Python: в наших примерах оно становится результатом вызова, если не был выполнен <code>return</code> со значением. Это не ноль и не пустая строка. Внешний <code>print(answer)</code> покажет слово <code>None</code>, но само по себе значение не станет числом. Если мы ожидали число, нужно проследить путь до оператора возврата.
        </p>
