      <Section number="07" title="Создаём и находим первый локальный commit">
        <Lead>
          Commit создаётся из подготовленного index. Перед необратимой записью в историю ещё раз сверим пути, строки и запуск программы, а затем найдём собственный результат.
        </Lead>
        <p>
          Начнём со статуса и имени текущей ветки. git branch --show-current выводит фактическое имя; мы не предполагаем заранее, что оно обязательно main или master. Убедимся, что до первого commit история этого clone ещё пуста, а в index лежат только main.py и .gitignore. Никакие новые ветки создавать не требуется.
        </p>
        <CodeBlock caption="Контроль перед записью" code={"git status\ngit branch --show-current\ngit diff --staged --name-only\ngit diff --staged"} />
        <p>
          Читаем оба блока staged diff. В main.py должна быть проверенная программа с приветствием, в .gitignore два правила из прошлого занятия. Если main.py менялся после запуска, сначала сохраняем его и снова запускаем проверенным Python 3.12. Затем повторяем git add -- main.py .gitignore и обе проверки staged diff: вчерашняя подготовленная версия не обновится автоматически.
        </p>
        <Callout tone="warn">
          <strong>Когда останавливаемся.</strong> Если виден лишний путь, непроверенный текст, секрет, неправильная подпись или уже существующий commit, не создаём запись по примеру. Сначала выясняем причину расхождения с начальным состоянием StudyHub.
        </Callout>
        <p>
          После проверки выполняем git commit -m с собственным коротким сообщением о том, что вошло в снимок. Параметр -m передаёт сообщение прямо в команде. Пример ниже показывает синтаксис, а конкретный текст выбираем по содержимому своего проекта. Команда создаёт локальную запись и не публикует её. Её краткий идентификатор появится в выводе Git и будет отличаться у разных учеников.
        </p>
        <CodeBlock caption="Независимый пример: записать подготовленный notes.txt" code={'git commit -m "Add first notes"'} />
        <p>
          После commit команда git log -1 --oneline показывает последнюю запись с коротким идентификатором и сообщением. Команда git show --format=short HEAD раскрывает последний commit: метаданные, включая Author, и изменения файлов. HEAD означает текущую последнюю запись ветки. Сверим имена двух файлов и автора с тем, что видели до commit.
        </p>
        <CodeBlock caption="После commit: подтверждаем историю, автора и состояние" code={"git log -1 --oneline\ngit show --format=short HEAD\ngit branch --show-current\ngit status\ngit diff --staged"} />
        <p>
          Если лишних файлов нет, git status сообщает о чистой рабочей папке, а git diff --staged ничего не выводит. Если мы исключали новый scratch.txt из index, он может оставаться untracked на диске: status покажет его, и это нормально. В обоих случаях не должно быть неожиданных staged-изменений. Пустой staged diff не означает, что index стал пустым: его содержимое теперь совпадает с последним commit. Наконец, запустим сохранённый main.py тем же проверенным способом Python 3.12, что и до commit, и увидим ожидаемое приветствие.
        </p>
        <Callout tone="info">
          <strong>Признак результата.</strong> Один новый локальный commit виден в log и show, автор и оба файла сверены, staged diff пуст, Python запускается. В status могут остаться только сознательно сохранённые untracked-файлы. Сетевой push не выполнялся.
        </Callout>
      </Section>

