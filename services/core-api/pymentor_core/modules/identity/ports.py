"""Identity storage contracts; device policy and cookies belong to use cases."""

from typing import Any
from typing import Protocol


class AccountReader(Protocol):
    def user_by_email(self, email: str) -> Any | None: ...
    def user_by_id(self, user_id: int) -> Any | None: ...


class LegacySessionRepository(AccountReader, Protocol):
    def session_by_token(self, token: str) -> Any | None: ...
    def ordered_sessions(self, user_id: int) -> list[Any]: ...
    def delete_session(self, session: Any) -> None: ...
    def add_session(self, user_id: int, token: str) -> None: ...
    def delete_token(self, token: str) -> None: ...
    def commit(self) -> None: ...
