"""Contracts consumed by Core; file and HTTP transports share these operations."""

from typing import Any
from typing import Protocol


class CourseCatalog(Protocol):
    def get_tracks_summary(self) -> list[dict[str, Any]]: ...
    def find_track(self, course_id: str) -> dict[str, Any] | None: ...
    def default_track_id(self) -> str: ...
    def get_content_revision(self) -> str: ...


class LessonContent(Protocol):
    def find_lesson(self, lesson_id: str) -> dict[str, Any] | None: ...
    def get_public_lessons(self, *args, **kwargs) -> list[dict[str, Any]]: ...


class PracticeSpec(Protocol):
    def find_task(self, task_id: str) -> dict[str, Any] | None: ...
    def find_lesson_by_task(self, task_id: str) -> dict[str, Any] | None: ...
